#!/usr/bin/env python3
"""Lint a GoHighLevel (or white-label GHL) Custom HTML paste block before it goes near a funnel step.

Every check here exists because it silently shipped at least once. Nothing in this
list throws an error in a browser: the page just quietly looks wrong.

    python3 block_lint.py <file> [<file>...] [--json] [--ban banned.txt]

--ban: optional house-style file, one phrase per line, optionally "phrase<TAB>reason".
       Lines starting with # are ignored. Matching is case-sensitive.

Exit 1 if any FAIL. WARN does not fail the run.
"""
import sys, re, json, os

# Defaults: never ship AI-authorship credits on a client page. Add your own house-style
# bans (old agency names, words the brand never uses) with --ban <file>.
BANNED_TEXT = [
    ("Built with Claude", "no AI-authorship credit on client pages"),
    ("BUILT WITH CLAUDE", "no AI-authorship credit on client pages"),
    ("Generated by AI", "no AI-authorship credit on client pages"),
]


def load_bans(path):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        phrase, _, why = line.partition("\t")
        out.append((phrase, why or "house-style ban"))
    return out

def lint(path, extra_bans=()):
    s = open(path, encoding="utf-8").read()
    fails, warns, info = [], [], []

    # 1. GHL page shell. Happens when the block was copied from the RENDERED page
    #    (view-source / devtools) instead of out of the Custom HTML box.
    #    A second window.__NUXT__={} BLANKS GHL's own runtime config.
    if "window.__NUXT__" in s:
        fails.append("GHL page shell present: window.__NUXT__ would blank GHL's own config. "
                     "Cut from the first <!----> after your closing tag up to your own appended code.")
    if s.count("<!---->") > 3:
        fails.append(f"{s.count('<!---->')} empty <!----> comments: scraped page shell, not a code block")
    if 'id="teleports"' in s:
        fails.append('<div id="teleports"> present: GHL shell, duplicates a real element id')

    # 2. CSS custom properties used but never defined. Invalid var() kills the WHOLE
    #    declaration, so font: ...var(--fd) silently renders 16px black Times.
    used = set(re.findall(r"var\(\s*(--[\w-]+)", s))
    declared = set(re.findall(r"(--[\w-]+)\s*:", s))
    # a var set from JS at runtime is legitimate, e.g. el.style.setProperty('--x', v)
    declared |= set(re.findall(r"setProperty\(\s*['\"](--[\w-]+)", s))
    missing = sorted(used - declared)
    if missing:
        fails.append("CSS variables used but never declared: " + ", ".join(missing[:8]) +
                     ". Any declaration using them is dropped entirely.")

    # 3. A variable declared ONLY inside a media query is undefined everywhere else.
    runtime = set(re.findall(r"setProperty\(\s*['\"](--[\w-]+)", s))
    css = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)  # comments can mention @media
    for var in sorted((used & declared) - runtime):
        base = False
        stack, pending_media = [], False
        for tok in re.finditer(r"@media|\{|\}|" + re.escape(var) + r"\s*:", css):
            t = tok.group(0)
            if t == "@media":
                pending_media = True
            elif t == "{":
                stack.append(pending_media)
                pending_media = False
            elif t == "}":
                if stack:
                    stack.pop()
            elif not any(stack):
                base = True
        if not base:
            fails.append(f"{var} is only declared inside a media query, so calc() using it "
                         f"is invalid at every other width")

    # 4. Google Fonts link. Without it the block falls back to Times on a page that
    #    does not already load the family.
    families = set(re.findall(r"font-family\s*:\s*['\"]?([A-Z][\w ]+)", s))
    families |= set(re.findall(r"--f[dum]\s*:\s*['\"]([A-Z][\w ]+)", s))
    has_link = "fonts.googleapis.com/css" in s
    webfonts = {f.strip() for f in families
                if f.strip() not in ("Times New Roman", "Arial", "Helvetica", "Georgia")}
    if webfonts and not has_link:
        fails.append("Web fonts referenced (" + ", ".join(sorted(webfonts)[:4]) +
                     ") but no fonts.googleapis.com stylesheet in the block")

    # 5. Tag balance. An unbalanced div silently eats the rest of the page.
    for tag in ("div", "script", "style"):
        o = len(re.findall(rf"<{tag}\b", s))
        c = len(re.findall(rf"</{tag}>", s))
        if o != c:
            fails.append(f"<{tag}> unbalanced: {o} open / {c} close")

    # 6. max-width media queries: only a real bug when the SAME selector+property is
    #    set in a WIDER block that comes after a narrower one, because then the wider
    #    rule wins at the narrow width. Plain source order is not enough to flag.
    def _body(start):
        d = 0
        i = s.index("{", start)
        for j in range(i, len(s)):
            if s[j] == "{":
                d += 1
            elif s[j] == "}":
                d -= 1
                if d == 0:
                    return s[i + 1:j]
        return ""

    seen = {}
    for m in re.finditer(r"@media[^{]*max-width\s*:\s*(\d+)px", s):
        w = int(m.group(1))
        for sel, decl in re.findall(r"([^{}]+)\{([^}]*)\}", _body(m.start())):
            for prop in re.findall(r"([a-z-]+)\s*:", decl):
                seen.setdefault((sel.strip(), prop), []).append(w)
    for (sel, prop), widths in seen.items():
        if len(widths) > 1 and widths[-1] > min(widths):
            fails.append(f"{sel[:40]} {{{prop}}} is set at max-width:{min(widths)}px but a "
                         f"max-width:{widths[-1]}px block sets it later, so the wider rule "
                         f"wins on small screens")
            break

    # 7. Brand rules.
    if "\u2014" in s:
        fails.append(f"{s.count(chr(8212))} em-dash(es): banned in all client copy")
    for needle, why in list(BANNED_TEXT) + list(extra_bans):
        if needle in s:
            fails.append(f"banned string {needle!r}: {why}")

    # 7b. Cookie consent flag on embedded GHL surveys/forms. "true" means the widget
    #     waits for a cookie banner the page does not have, so most visitors are never
    #     tracked. The GHL setting does not override what is in the paste block.
    if re.search(r'data-cookie-consent="true"', s):
        fails.append('data-cookie-consent="true" on an embed: ship "false" unless the page has a real '
                     'cookie banner wired to it')

    # 7c. CSS after markup. GHL paints before late <style> blocks parse, so the page
    #     renders unstyled for a frame and shifts (a large CLS hit).
    first_markup = re.search(r"<(div|section|main|header|h1|p|img|form|iframe)\b", s)
    if first_markup and re.search(r"<style\b", s[first_markup.start():]):
        warns.append("<style> block after the first markup: hoist all CSS above the markup to avoid "
                     "a first-paint layout shift")

    # 7d. Literal {{ inside scripts can be parsed by GHL as a merge field.
    for sc in re.findall(r"<script\b[^>]*>(.*?)</script>", s, re.S):
        if "{{" in sc:
            warns.append("literal '{{' inside a <script>: GHL may treat it as a merge field. "
                         "Write it as '\\x7b\\x7b' in JS strings")
            break

    # 7e. Copy tic that reads as AI-written.
    if re.search(r"\bit'?s not [^.]{1,40}, it'?s\b", s, re.I):
        warns.append("\"it's not X, it's Y\" construction: rewrite plainly")

    # 8. Images with width/height attributes but no CSS width:auto get squashed when
    #    CSS sets only height.
    for m in re.finditer(r"<img[^>]*\bwidth=\"\d+\"[^>]*>", s):
        tag = m.group(0)
        cls = re.search(r'class="([^"]+)"', tag)
        if cls and "width:auto" not in s:
            warns.append(f"<img class=\"{cls.group(1)}\"> has a width attribute; if CSS sets only "
                         f"height it will render at the attribute width. Add width:auto.")
            break

    # 9. Things that should be there.
    if "form_embed.js" in s and not re.search(r"https://[\w.-]+/js/form_embed\.js", s):
        warns.append("form_embed.js referenced without a full https URL on your GHL (or white-label) domain")
    if re.search(r"<!--(?!\s*\[)", s):
        warns.append("HTML comments present: they ship to the client's page source")

    info.append(f"{len(s):,} bytes")
    if has_link:
        info.append("web fonts linked")
    return fails, warns, info


def main():
    argv = sys.argv[1:]
    bans = []
    if "--ban" in argv:
        i = argv.index("--ban")
        bans = load_bans(argv[i + 1])
        del argv[i:i + 2]
    args = [a for a in argv if not a.startswith("--")]
    as_json = "--json" in argv
    if not args:
        sys.exit(__doc__)
    out, bad = {}, False
    for p in args:
        f, w, i = lint(p, bans)
        out[p] = {"fail": f, "warn": w, "info": i}
        bad = bad or bool(f)
        if not as_json:
            name = os.path.basename(p)
            print(f"\n{name}  [{'; '.join(i)}]")
            for x in f:
                print(f"   FAIL  {x}")
            for x in w:
                print(f"   warn  {x}")
            if not f and not w:
                print("   clean")
    if as_json:
        print(json.dumps(out, indent=1))
    sys.exit(1 if bad else 0)

if __name__ == "__main__":
    main()
